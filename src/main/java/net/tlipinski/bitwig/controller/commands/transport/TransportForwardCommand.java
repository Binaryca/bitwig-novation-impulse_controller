package net.tlipinski.bitwig.controller.commands.transport;

import com.bitwig.extension.controller.api.Transport;
import net.tlipinski.bitwig.controller.Controller;
import net.tlipinski.bitwig.controller.Midi;
import net.tlipinski.bitwig.controller.MidiCommand;

public class TransportForwardCommand implements MidiCommand {

    public TransportForwardCommand(Controller controller, Transport transport) {
        this.controller = controller;
        this.transport = transport;
        transport.getPosition().markInterested();
        controller.getHost().scheduleTask(this::tick, TICK_MS);
    }

    @Override
    public boolean triggersWhen(int statusByte, int data1, int data2) {
        // The buttons send 127 on press and 0 on release; nothing is sent
        // while held, so the hold repeat is generated by the ticker.
        return statusByte == Midi.CH1_CC
                && data1 == Midi.TRANSPORT_FORWARD;
    }

    @Override
    public void handle(int data1, int data2) {
        scrubbing = Midi.isPressed(data2);
        if (scrubbing) {
            step();
        }
    }

    private void tick() {
        try {
            if (scrubbing && ++tickCounter % TICKS_PER_STEP == 0) {
                step();
            }
        } finally {
            controller.getHost().scheduleTask(this::tick, TICK_MS);
        }
    }

    private void step() {
        // transport.fastForward() only steps and incPosition() interprets its
        // amount relative to the arrangement length (which jumps to the
        // start / end), so the step is computed from the current position and
        // set absolutely.
        double pos = transport.getPosition().get();
        double target = pos + SCRUB_BEATS;
        transport.setPosition(target);
    }

    private final Controller controller;
    private final Transport transport;
    private boolean scrubbing = false;
    private int tickCounter = 0;

    private static final long TICK_MS = 50;
    private static final int TICKS_PER_STEP = 3;
    private static final double SCRUB_BEATS = 1.0;
}
